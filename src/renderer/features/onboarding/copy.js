export function onboardingTranslator(getLanguage) {
  return source => {
    const yue = ONBOARDING_COPY[source] ?? source, language = getLanguage();
    return language === 'yue' ? yue : language === 'bilingual' && yue !== source ? `${source} · ${yue}` : source;
  };
}
